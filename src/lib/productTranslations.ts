export function translateCategoryName(slug: string, fallbackName: string, isEn: boolean): string {
  if (!isEn) return fallbackName;
  return CATEGORY_EN_MAP[slug] || fallbackName;
}

export function translateProductDescription(
  slug: string,
  fallbackDesc: string | null,
  isEn: boolean
): string {
  if (!isEn) {
    return (
      fallbackDesc ||
      "Perlengkapan sewa berstandar produksi profesional dari Maganta Kreasi. Hubungi kami untuk penawaran jadwal."
    );
  }
  return (
    PRODUCT_DESC_EN_MAP[slug] ||
    fallbackDesc ||
    "Professional-grade event rental equipment from Maganta Kreasi. Contact us for schedule availability."
  );
}

export function translatePriceUnit(unit: string, isEn: boolean): string {
  if (!isEn) return unit;
  const lower = unit.toLowerCase();
  if (lower === "paket") return "package";
  if (lower === "hari") return "day";
  return unit;
}
